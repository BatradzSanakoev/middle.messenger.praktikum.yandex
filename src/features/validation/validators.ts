// Объект с правилами валидации для каждого поля формы
// Каждое правило содержит regex и сообщение об ошибке
const validators = {
  // Имя: заглавная буква, буквы и дефис
  first_name: {
    regex: /^[A-ЯёA-Z][a-яёa-z-]*$/,
    message: "Имя должно начинаться с заглавной буквы, содержать только буквы и дефис",
  },
  // Фамилия: заглавная буква, буквы и дефис
  second_name: {
    regex: /^[A-ЯёA-Z][a-яёa-z-]*$/,
    message: "Фамилия должна начинаться с заглавной буквы, содержать только буквы и дефис",
  },
  // Логин: 3–20 символов, латиница, цифры, дефис, подчёркивание
  login: {
    regex: /^[a-zA-Z0-9_-]{3,20}$/,
    message: "Логин: 3–20 символов, латиница, цифры, дефис и подчёркивание, не может состоять только из цифр",
  },
  // Email: содержит @ и точку после него
  email: {
    regex: /^[a-zA-Z0-9]+@[a-zA-Z0-9]+\.[a-zA-Z0-9]+$/,
    message: "Введите корректный email (например: user@example.com)",
  },
  // Пароль: 8–40 символов, заглавная буква и цифра
  password: {
    regex: /^(?=.*[A-Z])(?=.*\d).{8,40}$/,
    message: "Пароль: 8–40 символов, хотя бы одна заглавная буква и одна цифра",
  },
  // Старый пароль: те же правила, что и password
  old_password: {
    regex: /^(?=.*[A-Z])(?=.*\d).{8,40}$/,
    message: "Пароль: 8–40 символов, хотя бы одна заглавная буква и одна цифра",
  },
  // Новый пароль: те же правила, что и password
  new_password: {
    regex: /^(?=.*[A-Z])(?=.*\d).{8,40}$/,
    message: "Пароль: 8–40 символов, хотя бы одна заглавная буква и одна цифра",
  },
  // Телефон: 10–15 цифр, возможен + в начале
  phone: {
    regex: /^\+?\d{10,15}$/,
    message: "Телефон: 10–15 цифр, возможен + в начале",
  },
  // Имя в чате: 1–50 символов, латиница, цифры, дефис, подчёркивание
  display_name: {
    regex: /^[a-zA-Z0-9_-]{1,50}$/,
    message: "Имя в чате: 1–50 символов, латиница, цифры, дефис и подчёркивание",
  },
  // Сообщение: не может быть пустым
  message: {
    regex: /.+/,
    message: "Сообщение не может быть пустым",
  },
} as const;

// Тип для ключей валидации (все ключи из validators)
export type ValidationKey = keyof typeof validators;

// Валидирует значение поля по правилу с данным ключом
// isEmptyAllowed — разрешает пустые значения (по умолчанию true, для message false)
export function validate(value: string, key: ValidationKey, isEmptyAllowed = true): string | null {
  const validator = validators[key];

  // Для message пустое значение всегда считается ошибкой
  if (key === "message" && value.length === 0) {
    return validator.message;
  }

  // Для остальных полей пустое значение валидно (если не запрещено isEmptyAllowed)
  if (isEmptyAllowed && value.length === 0) {
    return null;
  }

  // Проверяем значение по regex
  if (!validator.regex.test(value)) {
    return validator.message;
  }
  return null;
}
